#!/usr/bin/env python3
"""Rebuild frozen reports without changing retained outputs or opening new gates."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
from hashlib import sha256
import json
import os
from pathlib import Path
import platform
import subprocess
import sys
import tempfile
from time import monotonic

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--only', help='rerun one named analysis script and update its record')
    selected = parser.parse_args().only
    out = ROOT / 'verification/rebuilds'
    out.mkdir(parents=True, exist_ok=True)
    cases = [
        ('build_folio_index.py', [('output', 'data/derived/yale-canvas-index.json')]),
        ('analyze_corpus.py', [('json', 'results/baseline-zl3b.json'), ('markdown', 'results/baseline-zl3b.md')]),
        ('analyze_edge_morphology.py', [('json', 'results/p001-edge-morphology.json'), ('markdown', 'results/p001-edge-morphology.md')]),
        ('analyze_local_order.py', [('json', 'results/h004-local-order.json'), ('markdown', 'results/h004-local-order.md')]),
        ('analyze_contextual_comparator.py', [('json', 'results/h004b2-contextual-comparator.json'), ('markdown', 'results/h004b2-contextual-comparator.md')]),
        ('analyze_h004c_zg.py', [('json', 'results/h004c-zg-discovery-manifest.json'), ('markdown', 'results/h004c-zg-discovery.md'), ('sha256', 'results/h004c-zg-discovery-manifest.sha256.txt')]),
        ('analyze_h005_plant_anchors.py', [('json', 'results/h005-plant-anchors.json'), ('markdown', 'results/h005-plant-anchors.md'), ('sha256', 'results/h005-plant-anchors.sha256.txt')]),
        ('analyze_h006_fr3.py', [('json', 'results/h006-fr3-line-reset.json'), ('markdown', 'results/h006-fr3-line-reset.md'), ('sha256', 'results/h006-fr3-line-reset.sha256.txt')]),
        ('analyze_h007_pk23.py', [('json', 'results/h007-pk23-coverage.json'), ('markdown', 'results/h007-pk23-coverage.md'), ('sha256', 'results/h007-pk23-coverage.sha256.txt')]),
    ]
    record = {'started_utc': datetime.now(timezone.utc).isoformat(), 'python_version': platform.python_version(), 'method': 'sequential full frozen commands; compare every generated byte against retained artifacts', 'gate_policy': 'No gate overrides. H004-C/H005 IT events, H006 holdout residues, and H007 holdout classes remain sealed. H005 already-evaluated held-out retrieval is replayed under the frozen protocol.', 'runs': []}
    if selected:
        if selected not in {script for script, _ in cases}:
            raise SystemExit('unknown analysis script')
        if (out / 'record.json').is_file():
            record = json.loads((out / 'record.json').read_text())
        cases = [(script, outputs) for script, outputs in cases if script == selected]
    for script, outputs in cases:
        started = monotonic()
        with tempfile.TemporaryDirectory(prefix='publication-rebuild-', dir=out) as temp:
            temporary = Path(temp)
            args = [sys.executable, '-B', 'scripts/' + script]
            for flag, expected in outputs:
                args += ['--' + flag, str(temporary / Path(expected).name)]
            display = [x.replace(str(temporary), '<REBUILD_DIR>').replace(sys.executable, 'python3') for x in args]
            env = {**os.environ, 'PYTHONDONTWRITEBYTECODE': '1'}
            completed = subprocess.run(args, cwd=ROOT, env=env, capture_output=True, text=True, timeout=600)
            log = (completed.stdout + completed.stderr).replace(str(temporary), '<REBUILD_DIR>').replace(str(ROOT), '<PACKAGE>')
            if env.get('H007_PANDAS_PYTHON'):
                log = log.replace(env['H007_PANDAS_PYTHON'], '<PANDAS_PYTHON>')
            comparisons = []
            for _, expected in outputs:
                original = (ROOT / expected).read_bytes()
                built = temporary / Path(expected).name
                value = built.read_bytes() if built.is_file() else None
                comparisons.append({'artifact': expected, 'expected_sha256': sha256(original).hexdigest(), 'rebuilt_sha256': sha256(value).hexdigest() if value is not None else None, 'byte_identical': value == original})
            runtime_audit = None
            outputs_match = all(x['byte_identical'] for x in comparisons)
            if script == 'analyze_h007_pk23.py' and completed.returncode == 0 and not outputs_match:
                sys.path.insert(0, str(ROOT / 'src'))
                from voynich.naibbe_coverage import canonical_json_bytes, render_h007_markdown, render_sha256_sidecar
                retained = json.loads((ROOT / 'results/h007-pk23-coverage.json').read_bytes())
                rebuilt_bytes = (temporary / 'h007-pk23-coverage.json').read_bytes()
                rebuilt = json.loads(rebuilt_bytes)
                live_environment = rebuilt['stage0_author_controls']['environment']
                historical_environment = retained['stage0_author_controls']['environment']
                normalized = json.loads(rebuilt_bytes)
                normalized['stage0_author_controls']['environment'] = historical_environment
                scientific_match = canonical_json_bytes(normalized) == canonical_json_bytes(retained)
                actual_digest = sha256(rebuilt_bytes).hexdigest()
                render_match = (temporary / 'h007-pk23-coverage.md').read_text() == render_h007_markdown(rebuilt, actual_digest)
                sidecar_match = (temporary / 'h007-pk23-coverage.sha256.txt').read_text() == render_sha256_sidecar(actual_digest, 'h007-pk23-coverage.json')
                outputs_match = scientific_match and render_match and sidecar_match
                runtime_audit = {'sole_allowed_difference': '/stage0_author_controls/environment', 'historical_environment': historical_environment, 'actual_environment': live_environment, 'all_other_json_bytes_identical': scientific_match, 'actual_markdown_renderer_match': render_match, 'actual_checksum_match': sidecar_match}
            passed = completed.returncode == 0 and outputs_match
            item = {'command': ' '.join(display), 'exit_code': completed.returncode, 'elapsed_seconds': round(monotonic()-started, 3), 'passed': passed, 'outputs': comparisons}
            if runtime_audit is not None:
                item['runtime_metadata_comparison'] = runtime_audit
            record['runs'] = [old for old in record['runs'] if old['command'].split()[2] != 'scripts/' + script]
            record['runs'].append(item)
            (out / (script.removesuffix('.py') + '.txt')).write_text(log)
            record['all_completed_runs_passed'] = all(x['passed'] for x in record['runs'])
            (out / 'record.json').write_text(json.dumps(record, indent=2) + '\n')
            print(script, 'PASS' if passed else 'FAIL', item['elapsed_seconds'], flush=True)
            if not passed:
                raise SystemExit(1)
    record['completed_utc'] = datetime.now(timezone.utc).isoformat()
    record['all_nine_frozen_commands_scientific_outputs_match'] = len(record['runs']) == 9 and all(x['passed'] for x in record['runs'])
    (out / 'record.json').write_text(json.dumps(record, indent=2) + '\n')


if __name__ == '__main__':
    main()
